const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const file='/Users/raffribeiro/.codex/visualizations/2026/10/01/01a0f83c-7569-7dd0-ad8b-3e73b2b454df/munsell-selector.html';
const html=fs.readFileSync(file,'utf8');let reset,draws=0;
const context={$:()=>({addEventListener(type,fn){assert.equal(type,'click');reset=fn}}),drawLabPlane:()=>draws++};vm.createContext(context);
vm.runInContext(html.slice(html.indexOf('const labDefaultView='),html.indexOf("let markerSelectionSignature=")),context);
vm.runInContext(html.slice(html.indexOf('function projectLab('),html.indexOf('// Two restrained OKLab spectra')),context);
vm.runInContext(html.match(/\$\('\[data-action="lab-reset-zoom"\]'\)\.addEventListener\('click',[^\n]+/)[0],context);
const project=(a,b,l=50)=>context.projectLab({l,a,b},400,240);
const center=project(0,0),red=project(110,0),green=project(-110,0),yellow=project(0,110),blue=project(0,-110);
assert(red.x>center.x&&red.y>center.y,'Reference camera shows red at the lower right');
assert(green.x<center.x&&green.y<center.y,'Reference camera shows green at the upper left');
assert(blue.x<center.x&&blue.y>center.y,'Blue is at the lower left');
assert(yellow.x>center.x&&yellow.y<center.y,'Yellow is at the upper right');
assert(Math.abs(yellow.x-center.x)<Math.abs(red.x-center.x),'Red/green axis has the wider horizontal projection');
const redSlope=Math.abs((red.y-center.y)/(red.x-center.x)),yellowSlope=Math.abs((yellow.y-center.y)/(yellow.x-center.x));
assert(redSlope>.15&&redSlope<.20,'Red/green slope matches the reference angle');
assert(yellowSlope>2.5&&yellowSlope<2.8,'Blue/yellow slope matches the reference angle');
assert(project(0,0,100).y<center.y&&project(0,0,0).y>center.y,'White stays above black');
const initial=vm.runInContext('({...labView})',context);
vm.runInContext('Object.assign(labView,{yaw:0,pitch:.8,zoom:2,panX:.4,panY:-.3})',context);
let prevented=0;reset({preventDefault(){prevented++},stopPropagation(){prevented++}});
assert.deepEqual(vm.runInContext('({...labView})',context),initial,'Reset restores the same initial camera, including zoom and pan');
assert.equal(draws,1);assert.equal(prevented,2);
console.log('PASS: reference camera axis placement and tilt, vertical lightness, unchanged framing and Reset view returns to startup camera.');
