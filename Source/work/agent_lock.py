#!/usr/bin/env python3
"""Coordinate Codex and Claude working in this workspace at the same time.

Each agent claims the files it is about to edit. A claim is one lock file per
path in work/.agent-locks/, created atomically, so two agents can never hold the
same file. Shared build outputs (canonical fragment, generated pages, VERSION,
CHANGELOG release sections, ColorAtlas/App and Realase) sit behind one resource
lock, @build: hold it while installing into the canonical, running checks that
rebuild pages, and releasing. Edit your own claimed sources in parallel; take
@build one at a time.

  python3 work/agent_lock.py status
  python3 work/agent_lock.py claim  <agent> "<task>" <path|@build> [...]
  python3 work/agent_lock.py check  <agent> <path|@build> [...]   # exit 1 unless you hold all
  python3 work/agent_lock.py release <agent> [<path|@build> ...]  # no paths: release all yours
  python3 work/agent_lock.py note   <agent> "<text>"              # message for the other agent

agent is codex or claude. Paths are relative to the workspace root (absolute
paths inside it are accepted), so the macOS and VM mounts agree. A claim older
than STALE_HOURS may be taken over with --steal; the takeover is logged.
Every command rewrites work/AGENT_BOARD.md, the human-readable view.
"""
from __future__ import annotations
import datetime as dt, hashlib, json, os, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCKS = ROOT / 'work' / '.agent-locks'
BOARD = ROOT / 'work' / 'AGENT_BOARD.md'
LOG = LOCKS / 'log.jsonl'
AGENTS = {'codex', 'claude'}
STALE_HOURS = 3
RESOURCES = {'@build': 'canonical fragment, install scripts, generated pages, checks that rebuild, VERSION, CHANGELOG release entries, ColorAtlas/App and Realase'}


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def norm(p: str) -> str:
    if p in RESOURCES:
        return p
    if p.startswith('@'):
        sys.exit(f'unknown resource {p}; known: {", ".join(RESOURCES)}')
    q = Path(p)
    if q.is_absolute():
        try:
            q = q.resolve().relative_to(ROOT)
        except ValueError:
            sys.exit(f'{p} is outside the workspace; use @build for the canonical fragment and release folders')
    return q.as_posix().lstrip('./') or '.'


def lock_file(target: str) -> Path:
    return LOCKS / (hashlib.sha1(target.encode()).hexdigest()[:16] + '.json')


def read(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def claims():
    out = []
    for f in sorted(LOCKS.glob('*.json')):
        c = read(f)
        if c:
            c['_file'] = f
            out.append(c)
    return out


def age_hours(c) -> float:
    return (dt.datetime.now(dt.timezone.utc) - dt.datetime.fromisoformat(c['since'])).total_seconds() / 3600


def log(event: dict):
    LOCKS.mkdir(parents=True, exist_ok=True)
    with LOG.open('a') as f:
        f.write(json.dumps({'at': now(), **event}) + '\n')


def write_board():
    rows = claims()
    lines = ['# Agent board', '', 'Generated by `work/agent_lock.py` — do not edit by hand. Rules: AGENTS.md › Trabalho em paralelo.', '',
             f'Updated {now()}', '', '## Active claims', '']
    if rows:
        lines += ['| Agent | Target | Task | Since (UTC) |', '|---|---|---|---|']
        for c in sorted(rows, key=lambda c: (c['agent'], c['target'])):
            stale = ' (stale)' if age_hours(c) > STALE_HOURS else ''
            lines.append(f"| {c['agent']} | `{c['target']}` | {c['task']} | {c['since']}{stale} |")
    else:
        lines.append('None — the workspace is free.')
    events = []
    if LOG.exists():
        events = [json.loads(x) for x in LOG.read_text().splitlines()[-15:] if x.strip()]
    lines += ['', '## Recent activity', '']
    for e in reversed(events):
        what = e.get('text') or ', '.join(e.get('targets', []))
        lines.append(f"- {e['at']} · {e['agent']} · {e['event']}: {what}")
    if not events:
        lines.append('None yet.')
    BOARD.write_text('\n'.join(lines) + '\n')


def agent_arg(a: str) -> str:
    if a not in AGENTS:
        sys.exit(f'agent must be one of {sorted(AGENTS)}')
    return a


def cmd_claim(agent, task, targets, steal):
    LOCKS.mkdir(parents=True, exist_ok=True)
    got, blocked = [], []
    for t in map(norm, targets):
        f = lock_file(t)
        record = {'agent': agent, 'target': t, 'task': task, 'since': now()}
        for _ in range(2):
            try:
                fd = os.open(f, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
            except FileExistsError:
                held = read(f)
                if held and held['agent'] == agent:
                    got.append(t)  # already ours
                    break
                if held and steal and age_hours(held) > STALE_HOURS:
                    f.unlink(missing_ok=True)
                    log({'agent': agent, 'event': 'stole stale claim', 'targets': [t], 'text': f"{t} from {held['agent']} ({held['task']})"})
                    continue
                blocked.append((t, held))
                break
            else:
                with os.fdopen(fd, 'w') as out:
                    json.dump(record, out)
                got.append(t)
                break
    if blocked:
        # all or nothing: give back what this call took
        for t in got:
            held = read(lock_file(t))
            if held and held['agent'] == agent and held['task'] == task:
                lock_file(t).unlink(missing_ok=True)
        write_board()
        for t, held in blocked:
            who = f"{held['agent']} since {held['since']} ({held['task']})" if held else 'unreadable lock'
            print(f'BLOCKED {t}: held by {who}')
        sys.exit(1)
    log({'agent': agent, 'event': 'claim', 'targets': got, 'text': f"{task}: {', '.join(got)}"})
    write_board()
    print('CLAIMED ' + ', '.join(got))


def cmd_check(agent, targets):
    bad = []
    for t in map(norm, targets):
        held = read(lock_file(t))
        if not held or held['agent'] != agent:
            bad.append((t, held))
    for t, held in bad:
        print(f"NOT HELD {t}" + (f": {held['agent']} has it ({held['task']})" if held else ': unclaimed'))
    if bad:
        sys.exit(1)
    print('OK')


def cmd_release(agent, targets):
    mine = [c for c in claims() if c['agent'] == agent]
    want = set(map(norm, targets)) if targets else {c['target'] for c in mine}
    done = []
    for c in mine:
        if c['target'] in want:
            c['_file'].unlink(missing_ok=True)
            done.append(c['target'])
    if done:
        log({'agent': agent, 'event': 'release', 'targets': done})
    write_board()
    print('RELEASED ' + (', '.join(done) or 'nothing'))


def cmd_status():
    rows = claims()
    write_board()
    if not rows:
        print('No active claims.')
    for c in rows:
        stale = ' STALE' if age_hours(c) > STALE_HOURS else ''
        print(f"{c['agent']:6} {c['target']:48} {c['since']}{stale}  {c['task']}")


def main(argv):
    if not argv or argv[0] in {'-h', '--help'}:
        print(__doc__)
        return
    steal = '--steal' in argv
    argv = [a for a in argv if a != '--steal']
    cmd = argv[0]
    if cmd == 'status':
        cmd_status()
    elif cmd == 'claim' and len(argv) >= 4:
        cmd_claim(agent_arg(argv[1]), argv[2], argv[3:], steal)
    elif cmd == 'check' and len(argv) >= 3:
        cmd_check(agent_arg(argv[1]), argv[2:])
    elif cmd == 'release' and len(argv) >= 2:
        cmd_release(agent_arg(argv[1]), argv[2:])
    elif cmd == 'note' and len(argv) == 3:
        log({'agent': agent_arg(argv[1]), 'event': 'note', 'text': argv[2]})
        write_board()
        print('NOTED')
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == '__main__':
    main(sys.argv[1:])
